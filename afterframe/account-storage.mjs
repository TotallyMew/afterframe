import { AsyncLocalStorage } from 'node:async_hooks';
import { mkdirSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { migrateAccounts } from './account-migrations.mjs';

const sqliteSchema = `
  PRAGMA foreign_keys = ON;
  PRAGMA busy_timeout = 3000;
  CREATE TABLE IF NOT EXISTS accounts (
    id INTEGER PRIMARY KEY, username TEXT NOT NULL UNIQUE COLLATE NOCASE,
    salt TEXT NOT NULL, password_hash TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY, account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    expires INTEGER NOT NULL
  );
  CREATE TABLE IF NOT EXISTS library (
    account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    kind TEXT NOT NULL, key TEXT NOT NULL, value TEXT NOT NULL,
    PRIMARY KEY (account_id, kind, key)
  );
  CREATE TABLE IF NOT EXISTS provider_credentials (
    provider TEXT PRIMARY KEY, credential TEXT NOT NULL
  );
`;

const postgresSchema = `
  CREATE TABLE IF NOT EXISTS accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL,
    salt TEXT NOT NULL, password_hash TEXT NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS accounts_username_ci ON accounts (lower(username));
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY, account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    expires BIGINT NOT NULL
  );
  CREATE INDEX IF NOT EXISTS sessions_account ON sessions (account_id);
  CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions (expires);
  CREATE TABLE IF NOT EXISTS library (
    account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    kind TEXT NOT NULL, key TEXT NOT NULL, value TEXT NOT NULL, sequence BIGINT GENERATED ALWAYS AS IDENTITY,
    PRIMARY KEY (account_id, kind, key)
  );
  CREATE TABLE IF NOT EXISTS provider_credentials (provider TEXT PRIMARY KEY, credential TEXT NOT NULL);
  CREATE TABLE IF NOT EXISTS recovery_codes (
    account_id INTEGER PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    code_hash TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS release_snapshots (series_id BIGINT PRIMARY KEY, value TEXT NOT NULL);
  CREATE TABLE IF NOT EXISTS playback_versions (
    account_id INTEGER NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    kind TEXT NOT NULL, key TEXT NOT NULL, updated BIGINT NOT NULL,
    PRIMARY KEY (account_id, kind, key)
  );
`;

function sqliteStorage(path) {
  const database = new DatabaseSync(path);
  database.exec(sqliteSchema);
  migrateAccounts(database);
  const scope = new AsyncLocalStorage();
  let pending = Promise.resolve();
  function serialize(operation) {
    const next = pending.then(operation);
    pending = next.catch(() => {});
    return next;
  }
  return {
    prepare(sql) {
      const statement = database.prepare(sql);
      const run = (method, args) => scope.getStore() ? statement[method](...args) : serialize(() => statement[method](...args));
      return {
        get: (...args) => run('get', args),
        all: (...args) => run('all', args),
        run: (...args) => run('run', args),
      };
    },
    transaction(operation) {
      return serialize(async () => {
        database.exec('BEGIN IMMEDIATE');
        try {
          const result = await scope.run(true, operation);
          database.exec('COMMIT');
          return result;
        } catch (error) {
          database.exec('ROLLBACK');
          throw error;
        }
      });
    },
    async lockAccount() {},
    async lockRelease() {},
    async health() { await serialize(() => database.prepare('SELECT 1').get()); },
    close: () => serialize(() => database.close()),
  };
}

async function postgresStorage(connectionString) {
  const pool = new pg.Pool({ connectionString, connectionTimeoutMillis: 5000, allowExitOnIdle: true });
  pool.on('error', error => console.error('Account database connection error:', error.code || error.name));
  const scope = new AsyncLocalStorage();
  const query = (sql, args) => (scope.getStore() || pool).query(sql, args);
  async function transaction(operation) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await scope.run(client, operation);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally {
      client.release();
    }
  }
  try {
    await transaction(async () => {
      await query("SELECT pg_advisory_xact_lock(hashtext('afterframe-account-schema'))");
      await query(postgresSchema);
    });
  } catch (error) {
    await pool.end();
    throw new Error('Unable to initialize the PostgreSQL account store.', { cause: error });
  }
  return {
    prepare(sqliteSql, postgresSql = sqliteSql) {
      let index = 0;
      const sql = postgresSql.replaceAll('?', () => `$${++index}`);
      return {
        get: async (...args) => (await query(sql, args)).rows[0],
        all: async (...args) => (await query(sql, args)).rows,
        run: async (...args) => {
          const { rowCount } = await query(sql, args);
          return { changes: rowCount };
        },
      };
    },
    transaction,
    async lockAccount(id) { await query('SELECT id FROM accounts WHERE id = $1 FOR UPDATE', [id]); },
    async lockRelease(id) { await query('SELECT pg_advisory_xact_lock($1::bigint)', [id]); },
    async health() { await query('SELECT 1'); },
    close: () => pool.end(),
  };
}

export async function openAccountStorage() {
  if (process.env.AFTERFRAME_ACCOUNTS_DATABASE_URL) return postgresStorage(process.env.AFTERFRAME_ACCOUNTS_DATABASE_URL);
  if (process.env.AFTERFRAME_DB) return sqliteStorage(process.env.AFTERFRAME_DB);
  const directory = new URL('./data/', import.meta.url);
  mkdirSync(directory, { recursive: true });
  return sqliteStorage(fileURLToPath(new URL('accounts.sqlite', directory)));
}
